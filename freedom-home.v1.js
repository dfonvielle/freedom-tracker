  function fsSetOpen_(open) {
    if (!FS.mode) { return; }
    FS.open = !!open;
    if (!open) { fsCoachOpen_(false); }   // rail minimize also puts the coach away
    // ONE bubble, one meaning. Minimizing the rail unmounts any tool popup
    // (its widget launcher included — otherwise it stacks on ours in the
    // same corner and the bubble reopens the TOOL while the hint promises
    // the Freedom Page, with no path back to the rail's Continue button).
    // The chat itself is safe in localStorage; reopening routes back into
    // the current step, which remounts/resumes the right tool.
    if (!open && state.toolMountedBot) {
      FS.hadTool = true;
      unmountTool();
    }
    if (open && FS.hadTool) {
      FS.hadTool = false;
      window.setTimeout(function () { try { route(); } catch (e) {} }, 0);
    }
    if (rootEl) {
      // Minimized on a phone, the rail does NOT render as a scrunched inline
      // app (grandpa can't tell what he's looking at — Dave's phone round 2);
      // it collapses to a one-line hint card (fh-fs-hint ::before), exactly
      // like the standalone tool lessons' "tap the bubble" pattern.
      if (open) { rootEl.classList.add('fh-fs-on'); rootEl.classList.remove('fh-fs-hint'); }
      else { rootEl.classList.remove('fh-fs-on'); rootEl.classList.add('fh-fs-hint'); }
    }
    if (FS.mode === 'frame') {
      try {
        if (open) { FS.frameEl.classList.add('fh-fs-frame'); FS.pDoc.body.classList.add('fh-fs-lock'); }
        else { FS.frameEl.classList.remove('fh-fs-frame'); FS.pDoc.body.classList.remove('fh-fs-lock'); }
      } catch (e) {}
    } else {
      if (open) { document.body.classList.add('fh-fs-lock'); }
      else { document.body.classList.remove('fh-fs-lock'); }
    }
    if (FS.launcher) { FS.launcher.style.display = open ? 'none' : 'flex'; }
    if (FS.minBtn) { FS.minBtn.style.display = open ? 'flex' : 'none'; }
  }

  // Belt & braces: if a transformed/filtered ancestor traps position:fixed,
  // the "fullscreen" frame is still column-sized. Fall back to the plain
  // inline rail (today's behavior) instead of a locked half-takeover.
  function fsVerifyOrDegrade_() {
    if (FS.mode !== 'frame' || !FS.open) { return; }
    var ok = false;
    try {
      var r = FS.frameEl.getBoundingClientRect();
      var vw = FS.pWin.innerWidth, vh = FS.pWin.innerHeight;
      ok = (r.top <= 2 && r.left <= 2 && r.width >= vw - 4 && r.height >= vh * 0.85);
    } catch (e) {}
    if (!ok) { fsTeardown_(); }
  }

  function fsTeardown_() {
    fsSetOpen_(false);
    // Degrade means "be the plain inline rail" — that must stay VISIBLE, so
    // drop the minimized-hint state fsSetOpen_(false) just applied.
    if (rootEl) { rootEl.classList.remove('fh-fs-hint'); }
    fsCoachOpen_(false);
    if (FS.mode === 'frame') { fsCleanupParent_(FS.pWin, FS.pDoc); FS.launcher = null; }
    if (FS.launcher && FS.launcher.parentNode) { FS.launcher.parentNode.removeChild(FS.launcher); }
    if (FS.minBtn && FS.minBtn.parentNode) { FS.minBtn.parentNode.removeChild(FS.minBtn); }
    FS.mode = ''; FS.launcher = null; FS.minBtn = null;
    // A fast-paint may already have rendered mobile furniture (coach button
    // instead of the inline coach) — re-render on the inline path.
    if (rootEl && rootEl.querySelector('.fh-wrap')) { try { route(); } catch (e) {} }
  }

  // Remove whatever a PREVIOUS home lesson left in the parent (Systeme.io
  // swaps lessons SPA-style). Ours only — everything we inject is tagged.
  function fsCleanupParent_(pWin, pDoc) {
    try {
      if (pWin.__fhWatchdogId) { pWin.clearInterval(pWin.__fhWatchdogId); pWin.__fhWatchdogId = 0; }
      var owned = pDoc.querySelectorAll('[' + FS_OWNED + ']');
      for (var i = 0; i < owned.length; i++) {
        try { owned[i].parentNode && owned[i].parentNode.removeChild(owned[i]); } catch (e) {}
      }
      pDoc.body.classList.remove('fh-fs-lock');
      pDoc.body.classList.remove('fh-coach-open');
      var f = pDoc.querySelectorAll('.fh-fs-frame');
      for (var j = 0; j < f.length; j++) {
        try { f[j].classList.remove('fh-fs-frame'); } catch (e2) {}
      }
    } catch (e) {}
  }

