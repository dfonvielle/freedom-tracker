  function boot() {
    rootEl = document.getElementById(CONFIG.CONTAINER_ID);
    if (!rootEl) return;
    injectStyles();
    state.engine = rootEl.getAttribute('data-engine') || '';
    state.engineKey = rootEl.getAttribute('data-key') || '';
    state.draft = rootEl.getAttribute('data-draft') === '1';
    state.fullTrackerUrl = rootEl.getAttribute('data-full-tracker-url') || '';
    if (!FS.mode) { setupFullscreen_(); }   // once per page load (boot re-runs on retry)

    // TEST HOOK — mock transport: skip identity entirely.
    if (typeof window.__FH_MOCK_CALL === 'function') {
      state.identity = (window.__FH_MOCK_IDENTITY || { accountId: 'mock', email: 'mock@test', firstName: 'Testy' });
      state.token = 'mock-token';
      rootEl.innerHTML = shellLoading();
      loadState(false);
      return;
    }

    handleResetParam();
    captureMagicLinkToken();
    stripTokenFromUrl();
    state.token = readLS(LS.token);

    // FAST PAINT (same pattern as loader.v7): token + cached identity +
    // cached snapshot -> paint instantly, verify + refresh in background.
    var cachedId = readIdentityCache();
    var cachedSnap = state.token ? readStateCache() : null;
    if (state.token && cachedId && cachedSnap) {
      state.identity = cachedId;
      hydrateFromCache(cachedSnap.snapshot);
      if (cachedSnap.snapshot.firstName && !state.identity.firstName) {
        state.identity.firstName = cachedSnap.snapshot.firstName;
      }
      route();
      prefetchProgress_();
      verifyIdentityThenRefresh_(cachedId);
      return;
    }

    getIdentity().then(function (identity) {
      state.identity = identity;
      if (!state.token) { return attemptRecover(''); }
      var cached = readStateCache();
      if (cached) {
        hydrateFromCache(cached.snapshot);
        route();
        loadState(true);
      } else {
        rootEl.innerHTML = shellLoading();
        loadState(false);
      }
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }
